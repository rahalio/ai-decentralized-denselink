"""
API Server Domain Routes Generator

Generates platform/api-server/src/lib/routes/domain-routes.ts and
platform/api-server/src/domains/index.ts by rescanning the api-server domains
directory. Extension route excludes and imports are driven by x-codegen in OpenAPI specs.
"""

from pathlib import Path
from typing import Dict, List, Optional, Set

from ...base.generator import BaseGenerator, GenerateResult
from ...base.context import GenerationContext
from ...utils.file import ensure_directory, write_file
from ...utils.string import pascal_case, camel_case
from ...utils.x_codegen_extensions import (
    collect_domain_route_excludes,
    load_domain_specs,
)

from .discovery import discover_api_server_domains


# Legacy route excludes not yet moved to domain YAML (auth/callback special wiring).
# Identity auth is mounted via auth-routes-setup → auth.routes.ts (re-registers login/signup/…).
LEGACY_ROUTE_EXCLUDES: Dict[str, List[str]] = {
    "identity": [
        "authRoutes",
        "loginRoutes",
        "logoutRoutes",
        "signupRoutes",
        "sessionRoutes",
        "refreshRoutes",
        "tokenRoutes",
        "profileRoutes",
    ],
}


class ApiServerDomainRoutesGenerator(BaseGenerator):
    """Generates api-server domain-routes.ts and domains barrel index from rescan."""

    @property
    def name(self) -> str:
        return "API Server Domain Routes Generator"

    @property
    def version(self) -> str:
        return "2.0.0"

    @property
    def type(self) -> str:
        return "api_server_domain_routes"

    def generate(self, context: GenerationContext) -> GenerateResult:
        """Generate domain-routes.ts and domains/index.ts from discovered domains."""
        files: List[Path] = []
        warnings: List[str] = []

        project_root = context.config.paths.project_root
        api_server_src = project_root / "platform" / "api-server" / "src"
        domains_dir = api_server_src / "domains"
        lib_routes_dir = api_server_src / "lib" / "routes"

        domains = discover_api_server_domains(domains_dir)
        if not domains:
            context.logger.warn("No api-server domains found; skipping domain-routes and domains index")
            return GenerateResult(files=files, warnings=warnings)

        openapi_dir = Path(context.config.paths.openapi_dir)
        domain_specs = load_domain_specs(openapi_dir, context.config.domains)
        yaml_excludes = collect_domain_route_excludes(domain_specs)

        extension_domains = self._discover_extension_domains(domains_dir, domains)

        ensure_directory(lib_routes_dir)
        domain_routes_file = lib_routes_dir / "domain-routes.ts"

        import_lines: List[str] = []
        for domain in domains:
            var = f"{camel_case(domain)}Routes"
            import_lines.append(
                f'import * as {var} from "../../domains/{domain}/routes/index.js";'
            )

        extension_import_lines: List[str] = []
        extension_register_lines: List[str] = []
        for domain in extension_domains:
            export_name = f"{camel_case(domain)}ExtensionRoutes"
            extension_import_lines.append(
                f'import {{ {export_name} }} from "../../domains/{domain}/extensions/index.js";'
            )
            extension_register_lines.append(
                f'    await fastify.register({export_name});'
            )
            extension_register_lines.append(
                f'    console.log("[DEBUG] ✅ {domain} extension routes registered");'
            )

        module_entries: List[str] = []
        for domain in domains:
            var = f"{camel_case(domain)}Routes"
            excludes = self._merge_excludes(domain, yaml_excludes)
            if excludes:
                excludes_str = ", ".join(f'"{e}"' for e in excludes)
                module_entries.append(
                    f'  {{\n    domain: "{domain}", mod: {var},\n'
                    f'    exclude: [{excludes_str}],\n  }},'
                )
            else:
                module_entries.append(f'  {{ domain: "{domain}", mod: {var} }},')

        extension_imports_block = "\n".join(extension_import_lines)
        if extension_imports_block:
            extension_imports_block = extension_imports_block + "\n"

        extension_register_block = "\n".join(extension_register_lines)
        if extension_register_block:
            extension_register_block = extension_register_block + "\n"

        domain_routes_content = f'''/**
 * Domain routes – register all domain route modules.
 *
 * AUTO-GENERATED by codegen (api_server_domain_routes). Do not edit by hand.
 * Rescans platform/api-server/src/domains and includes only domains that have
 * routes/index.ts and dependencies/{{domain}}-ddd.dependencies.ts.
 * Extension excludes/imports from x-codegen.api-server.extensions in OpenAPI YAML.
 */

import type {{ FastifyInstance }} from "fastify";
import {{ registerDomainFromModule }} from "./route-registration.js";
{extension_imports_block}
// Static imports so the bundle includes all domain route modules
{chr(10).join(import_lines)}

const DOMAIN_MODULES: Array<{{
  domain: string;
  mod: Record<string, unknown>;
  exclude?: string[];
}}> = [
{chr(10).join(module_entries)}
];

export async function registerAllDomainRoutes(
  fastify: FastifyInstance,
): Promise<void> {{
  console.log("[DEBUG] Registering domain routes...");
  try {{
    for (const {{ domain, mod, exclude }} of DOMAIN_MODULES) {{
      await registerDomainFromModule(fastify, domain, mod, exclude ?? []);
    }}
{extension_register_block}    console.log("[DEBUG] ✅ All domain routes registered");
  }} catch (error: unknown) {{
    const err = error instanceof Error ? error : new Error(String(error));
    console.error("[DEBUG] ❌ Error registering domain routes:", err.message);
    if (err.stack) console.error(err.stack);
    throw error;
  }}
}}
'''
        write_file(domain_routes_file, domain_routes_content)
        files.append(domain_routes_file)

        domains_index_file = domains_dir / "index.ts"
        build_exports: List[str] = []
        type_exports: List[str] = []
        for domain in domains:
            pascal = pascal_case(domain)
            build_exports.append(
                f'export {{ build{pascal}DomainModule }} from "./{domain}/dependencies/{domain}-ddd.dependencies.js";'
            )
            type_exports.append(
                f'export type {{ {pascal}DomainModule }} from "./{domain}/dependencies/{domain}-ddd.dependencies.js";'
            )

        domains_index_content = f'''/**
 * Domains Barrel Export
 *
 * AUTO-GENERATED by codegen (api_server_domain_routes). Do not edit by hand.
 * Centralized exports for all domain dependency builders and types.
 */

// Export all domain dependency builders
{chr(10).join(build_exports)}

// Export all domain dependency types
{chr(10).join(type_exports)}
'''
        write_file(domains_index_file, domains_index_content)
        files.append(domains_index_file)

        context.logger.info(
            f"Generated api-server domain-routes and domains index with {len(domains)} domains (rescan)"
        )
        return GenerateResult(files=files, warnings=warnings)

    @staticmethod
    def _merge_excludes(domain: str, yaml_excludes: Dict[str, List[str]]) -> List[str]:
        merged: List[str] = []
        seen: Set[str] = set()
        for source in (LEGACY_ROUTE_EXCLUDES.get(domain, []), yaml_excludes.get(domain, [])):
            for item in source:
                if item not in seen:
                    seen.add(item)
                    merged.append(item)
        return merged

    @staticmethod
    def _discover_extension_domains(domains_dir: Path, domains: List[str]) -> List[str]:
        found: List[str] = []
        for domain in domains:
            ext_index = domains_dir / domain / "extensions" / "index.ts"
            if ext_index.exists():
                found.append(domain)
        return found
