"""
API Server System Routes Generator

Generates platform/api-server/src/lib/routes/system-routes.ts from:
- Discovered api-server domains (same source as domain-routes)
- Route examples extracted from each domain's OpenAPI bundled spec (paths)
"""

from pathlib import Path
from typing import List, Dict, Any

from ...base.generator import BaseGenerator, GenerateResult
from ...base.context import GenerationContext
from ...utils.file import ensure_directory, write_file
from .discovery import discover_api_server_domains
from ...utils.openapi import load_openapi_spec

# HTTP methods we care about (OpenAPI path item keys)
PATH_METHODS = ("get", "post", "put", "patch", "delete")


def _openapi_path_to_route_path(path: str) -> str:
    """Convert OpenAPI path /orgs/{orgId}/content/entries to Express-style /orgs/:orgId/content/entries."""
    return path.replace("{", ":").replace("}", "")


def _extract_route_examples_from_spec(spec: Dict[str, Any]) -> List[Dict[str, str]]:
    """Extract { method, path } list from OpenAPI spec paths."""
    examples: List[Dict[str, str]] = []
    paths = spec.get("paths") or {}
    for path_pattern, path_item in paths.items():
        if not isinstance(path_item, dict):
            continue
        route_path = _openapi_path_to_route_path(path_pattern)
        for method in PATH_METHODS:
            if method in path_item and isinstance(path_item[method], dict):
                examples.append({"method": method.upper(), "path": route_path})
    return examples


def _build_route_examples_by_domain(
    context: GenerationContext,
    discovered_domains: List[str],
) -> Dict[str, List[Dict[str, str]]]:
    """For each discovered domain, load its bundled spec and extract route examples."""
    route_examples: Dict[str, List[Dict[str, str]]] = {}
    config = context.config
    bundled_dir = config.paths.bundled_dir
    domain_config_by_name = {d.name: d for d in config.domains if d.enabled}

    for domain in discovered_domains:
        examples: List[Dict[str, str]] = []
        domain_config = domain_config_by_name.get(domain)
        if domain_config and domain_config.bundled_path:
            bundled_path = bundled_dir / domain_config.bundled_path
            if bundled_path.exists():
                try:
                    spec = load_openapi_spec(bundled_path)
                    examples = _extract_route_examples_from_spec(spec)
                except Exception as e:  # noqa: BLE001
                    context.logger.warn(
                        f"Could not load bundled spec for domain {domain}: {e}"
                    )
        route_examples[domain] = examples
    return route_examples


class ApiServerSystemRoutesGenerator(BaseGenerator):
    """Generates api-server system-routes.ts from discovered domains and OpenAPI specs."""

    @property
    def name(self) -> str:
        return "API Server System Routes Generator"

    @property
    def version(self) -> str:
        return "1.0.0"

    @property
    def type(self) -> str:
        return "api_server_system_routes"

    def generate(self, context: GenerationContext) -> GenerateResult:
        """Generate system-routes.ts from discovered domains and specs."""
        files: List[Path] = []
        warnings: List[str] = []

        project_root = context.config.paths.project_root
        api_server_src = project_root / "platform" / "api-server" / "src"
        lib_routes_dir = api_server_src / "lib" / "routes"

        domains_dir = api_server_src / "domains"
        domains = discover_api_server_domains(domains_dir)
        if not domains:
            context.logger.warn(
                "No api-server domains found; system-routes will have empty domains list"
            )

        route_examples = _build_route_examples_by_domain(context, domains)

        # Build routeExamples object for TypeScript: domain -> array of { method, path }
        route_examples_lines: List[str] = []
        for domain in sorted(route_examples.keys()):
            examples = route_examples[domain]
            entries = ", ".join(
                f'{{ method: "{e["method"]}", path: "{e["path"]}" }}' for e in examples
            )
            key = f'"{domain}"' if "-" in domain else domain
            route_examples_lines.append(f"      {key}: [{entries}],")
        route_examples_ts = (
            "\n".join(route_examples_lines)
            if route_examples_lines
            else "      // (no domain specs)"
        )

        # Sorted domains list for the /routes response
        domains_list_ts = ", ".join(f'"{d}"' for d in sorted(domains))

        ensure_directory(lib_routes_dir)
        system_routes_file = lib_routes_dir / "system-routes.ts"

        content = f'''/**
 * System Routes - Health check and routes listing
 *
 * AUTO-GENERATED by codegen (api_server_system_routes). Do not edit by hand.
 * Domains and routeExamples are derived from discovered api-server domains and
 * each domain's OpenAPI bundled spec.
 */

import type {{ FastifyInstance }} from "fastify";
import {{
  getCoreTableName,
  getBaseTableName,
  getAnalyticsTableName,
}} from "@ddd/adapters";
import {{ getRegisteredRoutes }} from "./route-registry.js";

/**
 * Register system routes (health check, routes listing)
 */
export function registerSystemRoutes(fastify: FastifyInstance): void {{
  // Health check (public - no auth required)
  fastify.get("/health", {{ config: {{ scope: "public" }} }}, async () => {{
    try {{
      const coreTable = getCoreTableName();
      const baseTable = getBaseTableName();
      const analyticsTable = getAnalyticsTableName();
      return {{
        status: "ok",
        database: "dynamodb",
        tables: {{
          core: coreTable,
          base: baseTable,
          analytics: analyticsTable,
        }},
      }};
    }} catch (error: unknown) {{
      const errorMessage =
        error instanceof Error ? error.message : String(error);
      fastify.log.warn({{ error: errorMessage }}, "Health check failed");
      return {{ status: "error", database: "disconnected", error: errorMessage }};
    }}
  }});

  // Routes listing endpoint (public)
  fastify.get("/routes", {{ config: {{ scope: "public" }} }}, async () => {{
    const domains = [
      {domains_list_ts}
    ];

    const routeExamples: Record<
      string,
      Array<{{ method: string; path: string; description?: string }}>
    > = {{
{route_examples_ts}
    }};

    return {{
      baseUrl: "http://localhost:4000",
      routePattern: "/orgs/:orgId/{{domain}}/{{resource}}",
      authentication:
        "All routes (except /health and /routes) require JWT token in Authorization header",
      domains: domains.sort(),
      routeExamples,
      systemRoutes: [
        {{ method: "GET", path: "/health", description: "Health check endpoint" }},
        {{ method: "GET", path: "/routes", description: "List available routes" }},
      ],
      note: "Replace :orgId with actual organization ID. All domain routes require authentication.",
    }};
  }});

  // Full route list for API tester page (public)
  fastify.get("/routes/full", {{ config: {{ scope: "public" }} }}, async () => {{
    const routes = getRegisteredRoutes();
    const byDomain: Record<
      string,
      Array<{{ method: string; path: string }}>
    > = {{}};
    const system: Array<{{ method: string; path: string }}> = [];
    for (const r of routes) {{
      const m = r.path.match(/^\\/orgs\\/:orgId\\/([^/]+)/);
      if (m) {{
        const domain = m[1];
        if (!byDomain[domain]) byDomain[domain] = [];
        byDomain[domain].push(r);
      }} else {{
        system.push(r);
      }}
    }}
    return {{
      baseUrl: "http://localhost:4000",
      total: routes.length,
      system,
      byDomain: Object.keys(byDomain)
        .sort()
        .reduce(
          (acc, k) => ({{ ...acc, [k]: byDomain[k] }}),
          {{}} as Record<string, Array<{{ method: string; path: string }}>>,
        ),
    }};
  }});
}}
'''
        write_file(system_routes_file, content)
        files.append(system_routes_file)

        context.logger.info(
            f"Generated api-server system-routes.ts with {len(domains)} domains from specs"
        )
        return GenerateResult(files=files, warnings=warnings)
